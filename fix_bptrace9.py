# -*- coding: utf-8 -*-
# doit6 §4: bptrace - БЕЗОПАСНАЯ РЕАЛИЗАЦИЯ ПОСЛЕ ТРЁХ ПАДЕНИЙ СЕРВЕРА.
#
# ИТОГ ТРЁХ ПОПЫТОК (все - падение/зависание сервера при включении):
#   1) патч 12 байт разрезал 7-байтовую инструкцию MOV RAX,[rip+..]  -> падение;
#   2) копирование RIP-относительной инструкции в трамплин меняло её базу -> падение;
#   3) вызов оригинала менял RSP -> security cookie оригинала не сходился -> зависание;
#      исправленная схема (стаб + хвостовой jmp, пролог копируется, cookie не ломается)
#      - тоже уронила сервер (00:36:52).
#
# ВЫВОД: фича в текущем виде НЕ ГОТОВА к выкатке. По ARCH.md 3.5 требование
# "по умолчанию выключен, байты патча не ставить вообще" выполняется ТОЛЬКО так:
# команда включения НЕ патчит код, а сообщает, что установка отключена.
#
# Что остаётся рабочим: разбор имени UFunction (FFrame::Node = UFunction*),
# схема учёта (thread_local + SRWLOCK на холодном пути) и весь разбор кода -
# они пригодятся, когда будет найден безопасный способ установки хука
# (например, через vtable-патч UObject::ProcessInternal на уровне указателя
# Func у конкретных UFunction, без патча кода процесса).
import io, sys

CPP = r'C:\Dev\ARK-Server-Plugins\TickProf\TickProf\TickProf.cpp'
src = io.open(CPP, 'r', encoding='utf-8', newline='').read()
NL = '\r\n' if '\r\n' in src else '\n'


def blk(t):
    return t.replace('\n', NL)


# 1) CmdBpTrace: установку хука отключаем - байты патча не ставятся
OLD_CMD = blk('''		if (!g_bp_target && !BpInstall())
		{
			LogLine("bptrace: хук не установился");
			return;
		}
		g_bp_on.store(true, std::memory_order_relaxed);
		g_bp_calls.store(0);
		LogLine("bptrace: включён (CET-трамплин 12 байт), счётчики обнулены");''')

NEW_CMD = blk('''		// УСТАНОВКА ХУКА ОТКЛЮЧЕНА.
		//
		// Три попытки установки (патч 12 байт; копирование RIP-относительной
		// инструкции в трамплин; хвостовой jmp со схемой без изменения RSP) -
		// каждая приводила к падению/зависанию сервера. Поэтому байты патча
		// НЕ СТАВЯТСЯ ВООБЩЕ (это требование ARCH.md 3.5: "по умолчанию
		// выключен, байты патча не ставить"), а команда сообщает о статусе.
		//
		// Всё остальное (разбор имени UFunction из FFrame::Node, схема учёта
		// thread_local + SRWLOCK на холодном пути) - готово и будет
		// использовано, как только появится безопасный способ установки.
		g_bp_on.store(false, std::memory_order_relaxed);
		LogLine("bptrace: установка хука ОТКЛЮЧЕНА (безопасный способ не найден: "
			"3 попытки привели к падению сервера); байты патча не установлены");
		LogLine("bptrace: имя UFunction доступно (FFrame::Node = UFunction*), "
			"счётчик готов, но данных пока нет");''')

assert OLD_CMD in src, 'тело CmdBpTrace не найдено'
src = src.replace(OLD_CMD, NEW_CMD, 1)

# 2) предупреждение компилятора о неиспользуемой BpInstall - оставляем функцию
#    (исходник полезен как заготовка), но помечаем
src = src.replace(blk('	bool BpInstall()\n	{'),
                  blk('	// ВНИМАНИЕ: функция НЕ вызывается (см. CmdBpTrace) - оставлена как\n'
                      '	// заготовка для будущей безопасной установки. Патч кода не ставится!\n'
                      '	bool BpInstall()\n	{'), 1)

io.open(CPP, 'w', encoding='utf-8', newline='').write(src)
print('bptrace: установка хука отключена (байты патча не ставятся), заготовка сохранена')
