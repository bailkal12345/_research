# -*- coding: utf-8 -*-
# Полная замена CmdBpTraceReport + CmdBpTraceCaller: дробные числа через BpFmt
# (мини-форматтер S() не умеет "{:.Nf}" - трактует как hex).
import io

CPP = r'C:\Dev\ARK-Server-Plugins\TickProf\TickProf\TickProf.cpp'
src = io.open(CPP, 'r', encoding='utf-8', newline='').read()
NL = '\r\n' if '\r\n' in src else '\n'

START = '\t// Отчёт: топ по вызовам'
END = '\t// Дамп флагов UFunction'
i = src.index(START)
j = src.index(END, i)

NEW = (
'\t// Дробные числа для мини-форматтера S(): он не умеет "{:.Nf}", поэтому\n'
'\t// формируем строку через snprintf и передаём аргументом "{}".\n'
'\tstd::string BpFmt(double v, int digits)\n'
'\t{\n'
'\t\tchar buf[64];\n'
'\t\tsnprintf(buf, sizeof(buf), digits == 1 ? "%.1f" : "%.2f", v);\n'
'\t\treturn buf;\n'
'\t}\n'
'\t// Отчёт: топ по вызовам и топ по self-времени (с долями).\n'
'\tvoid CmdBpTraceReport(RCONClientConnection*, RCONPacket*, UWorld*)\n'
'\t{\n'
'\t\tconst int64_t win_ms = GetTickCount64() - g_bp_win_start.load();\n'
'\t\tLogLine(S("bptrace: вызовов всего {} (окно {} с, QPC {} Гц)", g_bp_calls.load(), win_ms / 1000,\n'
'\t\t\tg_bp_qpc_freq));\n'
'\t\tstruct Row\n'
'\t\t{\n'
'\t\t\tstd::string name;\n'
'\t\t\tuint64_t calls;\n'
'\t\t\tdouble total_ms;\n'
'\t\t\tdouble self_ms;\n'
'\t\t\tbool script;\n'
'\t\t};\n'
'\t\tstd::vector<Row> rows;\n'
'\t\t{\n'
'\t\t\tAcquireSRWLockExclusive(&g_bp_lock);\n'
'\t\t\tfor (size_t i = 0; i < g_bp_slots; ++i)\n'
'\t\t\t{\n'
'\t\t\t\tconst BpSlot& s = g_bp_slotv[i];\n'
'\t\t\t\tif (s.calls == 0)\n'
'\t\t\t\t\tcontinue;\n'
'\t\t\t\trows.push_back({s.name, (uint64_t)s.calls,\n'
'\t\t\t\t\t(double)s.total_ticks * 1000.0 / (double)g_bp_qpc_freq,\n'
'\t\t\t\t\t(double)s.self_ticks * 1000.0 / (double)g_bp_qpc_freq, s.script});\n'
'\t\t\t}\n'
'\t\t\tReleaseSRWLockExclusive(&g_bp_lock);\n'
'\t\t}\n'
'\t\tLogLine(S("bptrace: функций с вызовами {}", rows.size()));\n'
'\t\tdouble sum_self = 0.0;\n'
'\t\tfor (const Row& r : rows)\n'
'\t\t\tsum_self += r.self_ms;\n'
'\t\tstd::vector<Row> by_calls = rows;\n'
'\t\tstd::sort(by_calls.begin(), by_calls.end(),\n'
'\t\t\t[](const Row& a, const Row& b) { return a.calls > b.calls; });\n'
'\t\tstd::vector<Row> by_self = rows;\n'
'\t\tstd::sort(by_self.begin(), by_self.end(),\n'
'\t\t\t[](const Row& a, const Row& b) { return a.self_ms > b.self_ms; });\n'
'\t\tLogLine("bptrace: ТОП-20 ПО ВЫЗОВАМ");\n'
'\t\tfor (size_t i = 0; i < by_calls.size() && i < 20; ++i)\n'
'\t\t{\n'
'\t\t\tconst Row& r = by_calls[i];\n'
'\t\t\tLogLine(S("bptrace:   {} вызовов={} total={}мс self={}мс мкс/вызов={} {}",\n'
'\t\t\t\tr.name, r.calls, BpFmt(r.total_ms, 1), BpFmt(r.self_ms, 1),\n'
'\t\t\t\tr.calls ? BpFmt(r.self_ms * 1000.0 / (double)r.calls, 2) : std::string("0"),\n'
'\t\t\t\tr.script ? "script" : "native"));\n'
'\t\t}\n'
'\t\tLogLine(S("bptrace: ТОП-20 ПО SELF-ВРЕМЕНИ (сумма self={} мс)", BpFmt(sum_self, 1)));\n'
'\t\tfor (size_t i = 0; i < by_self.size() && i < 20; ++i)\n'
'\t\t{\n'
'\t\t\tconst Row& r = by_self[i];\n'
'\t\t\tLogLine(S("bptrace:   {} self={}мс ({}%) вызовов={} мкс/вызов={} {}",\n'
'\t\t\t\tr.name, BpFmt(r.self_ms, 1),\n'
'\t\t\t\tBpFmt(sum_self > 0 ? 100.0 * r.self_ms / sum_self : 0.0, 1), r.calls,\n'
'\t\t\t\tr.calls ? BpFmt(r.self_ms * 1000.0 / (double)r.calls, 2) : std::string("0"),\n'
'\t\t\t\tr.script ? "script" : "native"));\n'
'\t\t}\n'
'\t}\n'
'\t// Топ вызывающих для функции (по рангу в топе self-времени или по подстроке имени).\n'
'\tvoid CmdBpTraceCaller(RCONClientConnection*, RCONPacket* packet, UWorld*)\n'
'\t{\n'
'\t\tconst std::string body = packet ? packet->Body.ToString() : "";\n'
'\t\tstd::string arg = body;\n'
'\t\tconst size_t sp = arg.find_last_of(\' \');\n'
'\t\tif (sp != std::string::npos)\n'
'\t\t\targ = arg.substr(sp + 1);\n'
'\t\tstruct Row\n'
'\t\t{\n'
'\t\t\tstd::string name;\n'
'\t\t\tint32_t slot;\n'
'\t\t\tdouble self_ms;\n'
'\t\t};\n'
'\t\tstd::vector<Row> rows;\n'
'\t\t{\n'
'\t\t\tAcquireSRWLockExclusive(&g_bp_lock);\n'
'\t\t\tfor (size_t i = 0; i < g_bp_slots; ++i)\n'
'\t\t\t{\n'
'\t\t\t\tconst BpSlot& s = g_bp_slotv[i];\n'
'\t\t\t\tif (s.calls == 0)\n'
'\t\t\t\t\tcontinue;\n'
'\t\t\t\trows.push_back({s.name, (int32_t)i,\n'
'\t\t\t\t\t(double)s.self_ticks * 1000.0 / (double)g_bp_qpc_freq});\n'
'\t\t\t}\n'
'\t\t\tReleaseSRWLockExclusive(&g_bp_lock);\n'
'\t\t}\n'
'\t\tstd::sort(rows.begin(), rows.end(),\n'
'\t\t\t[](const Row& a, const Row& b) { return a.self_ms > b.self_ms; });\n'
'\t\tint32_t target = -1;\n'
'\t\tconst bool by_rank = !arg.empty() && arg.find_first_not_of("0123456789") == std::string::npos;\n'
'\t\tif (by_rank)\n'
'\t\t{\n'
'\t\t\tconst size_t rank = (size_t)atoi(arg.c_str());\n'
'\t\t\tif (rank >= 1 && rank <= rows.size())\n'
'\t\t\t\ttarget = rows[rank - 1].slot;\n'
'\t\t}\n'
'\t\telse\n'
'\t\t{\n'
'\t\t\tfor (const Row& r : rows)\n'
'\t\t\t{\n'
'\t\t\t\tif (r.name.find(arg) != std::string::npos)\n'
'\t\t\t\t{\n'
'\t\t\t\t\ttarget = r.slot;\n'
'\t\t\t\t\tbreak;\n'
'\t\t\t\t}\n'
'\t\t\t}\n'
'\t\t}\n'
'\t\tif (target < 0)\n'
'\t\t{\n'
'\t\t\tLogLine(S("bptrace.caller: не найдена функция \'{}\' (ранг 1..{} или подстрока имени)", arg,\n'
'\t\t\t\trows.size()));\n'
'\t\t\treturn;\n'
'\t\t}\n'
'\t\tAcquireSRWLockExclusive(&g_bp_lock);\n'
'\t\tBpSlot& s = g_bp_slotv[target];\n'
'\t\tLogLine(S("bptrace.caller: {} (вызовов={}, self={}мс)", s.name, (uint64_t)s.calls,\n'
'\t\t\tBpFmt((double)s.self_ticks * 1000.0 / (double)g_bp_qpc_freq, 1)));\n'
'\t\tfor (int i = 0; i < BP_MAX_CALLERS; ++i)\n'
'\t\t{\n'
'\t\t\tconst int32_t cs = s.callers[i].slot;\n'
'\t\t\tif (cs == 0 || s.callers[i].count == 0)\n'
'\t\t\t\tcontinue;\n'
'\t\t\tconst uint64_t cnt = (uint64_t)s.callers[i].count;\n'
'\t\t\tstd::string cname;\n'
'\t\t\tif (cs == BP_CALLER_NATIVE)\n'
'\t\t\t\tcname = "<native/ProcessEvent-entry>";\n'
'\t\t\telse if (cs == BP_CALLER_UNKNOWN)\n'
'\t\t\t\tcname = "<вызывающий не опознан>";\n'
'\t\t\telse if (cs >= 0 && (size_t)cs < g_bp_slotv.size())\n'
'\t\t\t\tcname = g_bp_slotv[cs].name;\n'
'\t\t\tLogLine(S("bptrace.caller:   {} вызовов={} ({}%)", cname, cnt,\n'
'\t\t\t\tBpFmt((uint64_t)s.calls ? 100.0 * (double)cnt / (double)s.calls : 0.0, 1)));\n'
'\t\t}\n'
'\t\tReleaseSRWLockExclusive(&g_bp_lock);\n'
'\t}\n').replace('\n', NL)

src = src[:i] + NEW + src[j:]
io.open(CPP, 'w', encoding='utf-8', newline='').write(src)
print('отчётные функции заменены целиком')
