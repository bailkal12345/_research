# -*- coding: utf-8 -*-
# doit6 §4 (исправление 5): обход ограничения "__asm нет в x64 MSVC".
#
# Проблема: обработчик обязан вызвать оригинал так, чтобы RSP при входе в
# оригинал ТОЧНО совпал с ожидаемым (иначе security cookie не сойдётся).
# Решение без asm: выделяем shadow space средствами C++ (alloca-подобный приём
# через локальный массив, компилятор сам сдвинет RSP на нужную величину) и
# ПРЫГАЕМ в трамплин обычным C++-вызовом обработчика-обёртки.
#
# Схема (x64, shadow space = 32 байта):
#   H_ProcessInternal (вход через jmp, RSP не тронут):
#       volatile char pad[32];  // кадр выравнивается компилятором
#       ...подсчёт...
#       BpJumpToOriginal();     // ассемблерный переход, СОХРАНЯЯ RSP
#   BpJumpToOriginal(): mov r11, [g_bp_trampoline]; jmp r11  (сырой машинный код)
#   Трамплин: PUSH RBX; PUSH RSI; PUSH RDI; SUB RSP,0x80; jmp target+11
#   => оригинал видит идентичный RSP, cookie сходится.
#
# BpJumpToOriginal реализуется как вызов указателя на СГЕНЕРИРОВАННЫЙ машинный
# код (mov r11,imm64; jmp r11) - indirect call, но RSP при этом меняется
# (call кладёт адрес возврата) => это ломает cookie.
# Решение: сгенерированный код - это "mov r11,imm64; jmp r11" и мы вызываем его
# ЧЕРЕЗ tail-call: компилятор MSVC на x64 генерирует jmp для хвостового вызова
# функции-указателя, если функция помечена как __declspec(noinline) + возвращает
# void. Для этого делаем обёртку: __forceinline -> нельзя. Значит делаем обычный
# (не tail) вызов, но тогда CALL кладёт ret-адрес => RSP-8.
# Компенсация: перед вызовом делаем sub rsp,8 эквивалент (через локальный буфер),
# после - возвращаем. Ниже это реализовано через выровненный локальный буфер, который
# компилятор разместит так, что RSP вернётся к исходному после выхода из функции -
# т.е. компилятор сам восстановит RSP, а нам нужно лишь, чтобы ОРИГИНАЛ увидел
# правильный RSP. Поэтому вызов оригинала делаем ПОСЛЕ восстановления RSP:
# используем "setjmp/longjmp-подобный" трюк не нужен - достаточно, чтобы
# сгенерированный код ПЕРЕДАЛ УПРАВЛЕНИЕ (jmp), а не возвращался.
# Для этого применяем SEH-подобный приём: jmp через сгенерированный код с
# НУЛЕВЫМ возвратом невозможно, поэтому используем прямой вызов трамплина и
# корректно восстанавливаем RSP через стековый баланс:
#     push/call -> ret-адрес в стеке, но оригинал ожидает RSP-8 (ret-адрес) =>
#     это ровно то, что нужно! Оригинал ProcessInternal при вызове через call
#     имеет на стеке ret-адрес, т.е. RSP такой же, как при обычном вызове.
# Значит: вызываем трамплин обычным C++-вызовом (call), и трамплин выполняет
# пролог оригинала и прыгает на target+11, а RET трамплина возвращает нас.
# Тогда RSP при входе в оригинал = RSP_вызова - 8 (ret) - 24 (push x3) - 0x80
# = ровно как ожидает оригинал (у него на стеке ret от ProcessInternal).
import io, sys

CPP = r'C:\Dev\ARK-Server-Plugins\TickProf\TickProf\TickProf.cpp'
src = io.open(CPP, 'r', encoding='utf-8', newline='').read()
NL = '\r\n' if '\r\n' in src else '\n'


def blk(t):
    return t.replace('\n', NL)


OLD = blk('''		// Вызов оригинала БЕЗ изменения RSP: иначе security cookie оригинала
		// (XOR RAX,[0x1448AFB30], RSP) не сойдётся и функция зависнет.
		// Схема: sub rsp,0x20 (shadow) -> call счётчика -> add rsp,0x20 -> jmp трамплин.
		// Трамплин выполняет пролог оригинала (PUSH x3; SUB RSP,0x80) и прыгает
		// на target+11, поэтому оригинал видит ИДЕНТИЧНЫЙ RSP.
		__asm
		{
			sub  rsp, 20h
		}
		{
			std::string nm;
			if (BpFunctionName(frame, nm))
				BpNote(nm);
		}
		__asm
		{
			add  rsp, 20h
			mov  r11, g_bp_trampoline
			jmp  r11
		}
	}''')

NEW = blk('''		// Подсчёт вызовов (до вызова оригинала).
		if (g_bp_on.load(std::memory_order_relaxed))
		{
			std::string nm;
			if (BpFunctionName(frame, nm))
				BpNote(nm);
		}
		// Вызов оригинала.
		//
		// КРИТИЧНО про RSP: оригинал вычисляет security cookie как
		// XOR RAX(=[0x1448AFB30]), RSP, где RSP - значение ПОСЛЕ пролога
		// (PUSH x3; SUB RSP,0x80). Трамплин выполняет ровно этот пролог и
		// прыгает на target+11, поэтому при входе в оригинал RSP должен быть
		// таким же, как при обычном вызове (call кладёт ret-адрес, PUSH x3 и
		// SUB RSP,0x80 - то же, что делает оригинал).
		//
		// Поэтому трамплин вызывается ОБЫЧНЫМ C++-вызовом функции-указателя:
		// call даёт на стеке ret-адрес (как и ожидает оригинал), а трамплин
		// выполняет PUSH RBX/RSI/RDI; SUB RSP,0x80; jmp target+11.
		// Оригинал завершается ret'ом по адресу, который положил CALL.
		typedef void(__fastcall* Fn)(void*, void*, void*);
		reinterpret_cast<Fn>(_o_ProcessInternal)(self, frame, result);
	}''')

assert OLD in src, 'текущий вид обработчика не найден'
src = src.replace(OLD, NEW, 1)
io.open(CPP, 'w', encoding='utf-8', newline='').write(src)
print('bptrace: вызов оригинала сделан обычным call через трамплин (RSP как при штатном вызове)')
