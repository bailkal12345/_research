def fix_comment(m):
    text = m.group(0).rstrip()
    key = text[2:].strip()
    base_indent = ''
    return base_indent + '//' + en

def comment_repl(m):
    text = m.group(0)
    r = text.rstrip()
    key = r[2:].strip()
    if key in CMT:
        return '//' + CMT[key]
    return m.group(0)

src = re.sub(r'//[^\r\n]*', comment_repl, src)

# ---- pass 2: string literals
lit_missing = []

def lit_repl(m):
    body = m.group(1)
    if body in LIT:
        return '"' + LIT[body] + '"'
    if any('\u0400' <= c <= '\u04ff' for c in body) or any('\u4e00' <= c <= '\u9fff' for c in body):
        lit_missing.append(body)
    return m.group(0)

src = re.sub(r'"((?:[^"\\\n\r]|\\.)*)"', lit_repl, src)
